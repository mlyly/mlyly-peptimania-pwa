/**
 * Notification opt-in contract.
 *
 * Notifications are the only optional feature that can leave the device: a
 * push relay must receive a browser-issued push endpoint, its encryption keys
 * and the reminder schedule. The settings card therefore records an explicit,
 * versioned consent before reminders can be enabled.
 *
 * Bumping `NOTIFICATIONS_CONSENT_VERSION` invalidates every previous consent
 * and makes the settings card ask again with the updated disclosure.
 */

/** Version of the disclosure shown in Settings → Notifications. */
export const NOTIFICATIONS_CONSENT_VERSION = "2026-11-14";

/**
 * Data the relay may receive when background push is enabled. Keep this list
 * in sync with the disclosure card and `docs/notifications-plan.md`.
 */
export const NOTIFICATION_RELAY_DATA = [
    "A push endpoint and encryption keys generated by your browser",
    "Your time zone and the reminder times you choose",
    "Standard request metadata such as your IP address (never used for analytics)",
    "In generic mode: nothing else — the relay sends only “a dose is due”",
    "In detailed mode: an end-to-end encrypted reminder payload the relay cannot read",
] as const;

/** Data that is never sent to the relay. */
export const NOTIFICATION_LOCAL_ONLY_DATA = [
    "Dose history and scheduled dose details",
    "Inventory, lots and prices",
    "Body measurements and notes",
    "Backup files and your local database",
    "Your name, email or any account identity",
] as const;

/** True when a stored consent is non-empty and matches the current version. */
export function hasCurrentNotificationConsent(
    consentAt: string | null,
    consentVersion: string | null,
    now: number = Date.now()
): boolean {
    if (!consentAt || consentVersion !== NOTIFICATIONS_CONSENT_VERSION) return false;
    const time = Date.parse(consentAt);
    // Small clock-skew allowance, mirroring `lib/legal/terms.ts`.
    return Number.isFinite(time) && time <= now + 60_000;
}
